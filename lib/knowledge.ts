export function findDrugs(question: string): DrugProfile[] {
  const q = question.toLowerCase();
  const ids = new Set<string>();
  for (const d of DRUGS) {
    if (d.keys.some((k) => q.includes(k.toLowerCase()))) ids.add(d.id);
  }
  if (/降压药|血压药|降压的/.test(q)) ids.add("amlodipine");
  if (/降糖药|血糖药|降糖的/.test(q)) ids.add("metformin");
  if (/降脂药|血脂药|调脂药|降脂的/.test(q)) ids.add("atorvastatin");
  return DRUGS.filter((d) => ids.has(d.id));
}

export function profilesForNames(names: string[]): DrugProfile[] {
  const ids = new Set<string>();
  for (const name of names) {
    const lower = name.toLowerCase();
    for (const d of DRUGS) {
      if (d.keys.some((k) => lower.includes(k.toLowerCase()))) ids.add(d.id);
    }
  }
  return DRUGS.filter((d) => ids.has(d.id));
}

